@router.websocket("/chat/{session_id}")
async def chat_websocket(websocket: WebSocket, session_id: str):
    """
    WebSocket endpoint for real-time chat with the assistant.
    """
    await chat_manager.connect(websocket, session_id)
    
    try:
        while True:
            # Receive message from client
            data = await websocket.receive_text()
            message_data = json.loads(data)
            
            # Validate message structure
            if "query" not in message_data or "user_id" not in message_data:
                await chat_manager.send_message(session_id, {
                    "type": "error",
                    "message": "Invalid message format"
                })
                continue
            
            # Create assistant query
            query = AssistantQuery(
                session_id=session_id,
                user_id=message_data["user_id"],
                query_text=message_data["query"],
                query_type=QueryType(message_data.get("query_type", "general_security")),
                time_window_hours=message_data.get("time_window_hours", 24)
            )
            
            # Send typing indicator
            await chat_manager.send_message(session_id, {
                "type": "typing",
                "message": "Assistant is thinking..."
            })
            
            # Process query
            try:
                response = await assistant_service.process_query(query)
                
                # Send response
                await chat_manager.send_message(session_id, {
                    "type": "response",
                    "query_id": query.query_id,
                    "response_id": response.response_id,
                    "message": response.response_text,
                    "confidence": response.confidence_score,
                    "insights": response.key_insights,
                    "actions": response.recommended_actions,
                    "suggestions": response.suggested_queries,
                    "processing_time_ms": response.processing_time_ms
                })
                
            except Exception as e:
                logger.error(f"Error processing chat query: {e}")
                await chat_manager.send_message(session_id, {
                    "type": "error",
                    "message": "Sorry, I encountered an error processing your request."
                })
    
    except WebSocketDisconnect:
        chat_manager.disconnect(session_id)
    except Exception as e:
        logger.error(f"WebSocket error for session {session_id}: {e}")
        chat_manager.disconnect(session_id)


@router.get("/health")
async def health_check():
    """
    Health check endpoint for the GenAI assistant service.
    """
    try:
        # Test LLM connectivity
        test_response = await assistant_service.llm_service.generate_response(
            prompt="Test connectivity",
            max_tokens=10
        )
        
        llm_status = "healthy" if test_response["success"] else "degraded"
        
        health_status = {
            "status": "healthy",
            "timestamp": datetime.utcnow().isoformat(),
            "services": {
                "llm_service": llm_status,
                "rag_service": "healthy",
                "chat_manager": f"{len(chat_manager.active_connections)} active sessions"
            },
            "model_info": {
                "model_name": assistant_service.llm_service.model_name,
                "base_url": assistant_service.llm_service.base_url
            }
        }
        
        return health_status
        
    except Exception as e:
        logger.error(f"Health check failed: {e}")
        return {
            "status": "unhealthy",
            "timestamp": datetime.utcnow().isoformat(),
            "error": str(e)
        }


def _get_query_type_description(query_type: QueryType) -> str:
    """Get description for query types"""
    descriptions = {
        QueryType.THREAT_ANALYSIS: "Analyze threats and security incidents with AI-powered insights",
        QueryType.NETWORK_INVESTIGATION: "Investigate network traffic patterns and anomalies",
        QueryType.INCIDENT_RESPONSE: "Get guidance for incident response and containment",
        QueryType.GENERAL_SECURITY: "General cybersecurity questions and advice",
        QueryType.MITRE_LOOKUP: "Look up MITRE ATT&CK techniques and tactics",
        QueryType.TREND_ANALYSIS: "Analyze security trends and patterns over time"
    }
    return descriptions.get(query_type, "Security-related query")
