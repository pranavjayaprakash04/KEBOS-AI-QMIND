# WebSocket connection manager for real-time chat
class ChatConnectionManager:
    def __init__(self):
        self.active_connections: Dict[str, WebSocket] = {}

    async def connect(self, websocket: WebSocket, session_id: str):
        await websocket.accept()
        self.active_connections[session_id] = websocket
        logger.info(f"Chat session {session_id} connected")

    def disconnect(self, session_id: str):
        if session_id in self.active_connections:
            del self.active_connections[session_id]
            logger.info(f"Chat session {session_id} disconnected")

    async def send_message(self, session_id: str, message: dict):
        if session_id in self.active_connections:
            try:
                await self.active_connections[session_id].send_text(json.dumps(message))
            except:
                self.disconnect(session_id)

chat_manager = ChatConnectionManager()


@router.post("/query", response_model=AssistantResponse)
async def process_query(
    query: AssistantQuery,
    current_user: dict = Depends(get_current_user)
):
    """
    Process a query through the GenAI assistant with RAG-enhanced context.
    """
    try:
        # Validate user has access to query
        if query.user_id != current_user["user_id"]:
            raise HTTPException(status_code=403, detail="Access denied")
        
        # Process query through assistant
        response = await assistant_service.process_query(query)
        
        # Log the interaction (simplified)
        logger.info(f"User {current_user['user_id']} submitted query {query.query_id}")
        
        return response
        
    except Exception as e:
        logger.error(f"Error processing assistant query: {e}")
        raise HTTPException(status_code=500, detail="Query processing failed")


